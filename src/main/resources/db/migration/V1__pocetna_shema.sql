-- Početna shema baze. Od sada se baza mijenja samo novim migracijama (V2__..., V3__...),
-- nikad izmjenom ove datoteke, jer je već izvršena na serveru.

CREATE TABLE tvrtka (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv VARCHAR(255) NOT NULL
);

CREATE TABLE korisnik (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime            VARCHAR(255) NOT NULL,
    email          VARCHAR(255) NOT NULL UNIQUE,
    lozinka_hash   VARCHAR(255) NOT NULL,
    uloga          VARCHAR(255) NOT NULL CHECK (uloga IN ('VLASNIK', 'CLAN')),
    email_potvrden BOOLEAN      NOT NULL,
    tvrtka_id      BIGINT       NOT NULL REFERENCES tvrtka (id)
);

CREATE TABLE email_kod (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255)                NOT NULL,
    kod_hash   VARCHAR(255)                NOT NULL,
    svrha      VARCHAR(255)                NOT NULL CHECK (svrha IN ('POTVRDA_EMAILA', 'POZIV', 'RESET_LOZINKE')),
    tvrtka_id  BIGINT REFERENCES tvrtka (id),
    istjece    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    pokusaji   INTEGER                     NOT NULL,
    iskoristen BOOLEAN                     NOT NULL
);

CREATE TABLE paket (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv     VARCHAR(255)   NOT NULL,
    opis      VARCHAR(2000),
    cijena    NUMERIC(38, 2) NOT NULL,
    tvrtka_id BIGINT         NOT NULL REFERENCES tvrtka (id)
);

CREATE TABLE dodatak (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv     VARCHAR(255)   NOT NULL,
    cijena    NUMERIC(38, 2) NOT NULL,
    tvrtka_id BIGINT         NOT NULL REFERENCES tvrtka (id)
);

CREATE TABLE suradnik (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime       VARCHAR(255) NOT NULL,
    uloga     VARCHAR(255) NOT NULL CHECK (uloga IN ('FOTOGRAF', 'VIDEOGRAF', 'DRON', 'ASISTENT', 'OSTALO')),
    telefon   VARCHAR(255),
    email     VARCHAR(255),
    napomena  VARCHAR(2000),
    tvrtka_id BIGINT       NOT NULL REFERENCES tvrtka (id)
);

CREATE TABLE vjencanje (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datum              DATE           NOT NULL,
    lokacija           VARCHAR(255),
    mlada_ime          VARCHAR(255),
    mlada_prezime      VARCHAR(255),
    mlada_telefon      VARCHAR(255),
    mlada_email        VARCHAR(255),
    mlada_adresa       VARCHAR(255),
    mladozenja_ime     VARCHAR(255),
    mladozenja_prezime VARCHAR(255),
    mladozenja_telefon VARCHAR(255),
    mladozenja_email   VARCHAR(255),
    mladozenja_adresa  VARCHAR(255),
    paket_id           BIGINT REFERENCES paket (id),
    dogovorena_cijena  NUMERIC(38, 2) NOT NULL,
    status             VARCHAR(255)   NOT NULL
        CHECK (status IN ('UPIT', 'POTVRDENO', 'ODRADENO', 'ISPORUCENO', 'OTKAZANO')),
    rok_isporuke       DATE,
    izvor_upita        VARCHAR(255)
        CHECK (izvor_upita IN ('INSTAGRAM', 'FACEBOOK', 'GOOGLE', 'WEB_STRANICA', 'PREPORUKA', 'OSTALO')),
    napomene           VARCHAR(4000),
    broj_gostiju       INTEGER,
    ostali_troskovi    NUMERIC(38, 2),
    link_galerije      VARCHAR(1000),
    tvrtka_id          BIGINT         NOT NULL REFERENCES tvrtka (id)
);

CREATE TABLE vjencanje_dodatak (
    vjencanje_id BIGINT NOT NULL REFERENCES vjencanje (id),
    dodatak_id   BIGINT NOT NULL REFERENCES dodatak (id),
    PRIMARY KEY (vjencanje_id, dodatak_id)
);

CREATE TABLE stavka_rasporeda (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vrijeme      TIME(6),
    naziv        VARCHAR(255) NOT NULL,
    adresa       VARCHAR(255),
    napomena     VARCHAR(2000),
    vjencanje_id BIGINT       NOT NULL REFERENCES vjencanje (id)
);

CREATE TABLE clan_ekipe (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vjencanje_id BIGINT       NOT NULL REFERENCES vjencanje (id),
    suradnik_id  BIGINT       NOT NULL REFERENCES suradnik (id),
    uloga        VARCHAR(255) NOT NULL CHECK (uloga IN ('FOTOGRAF', 'VIDEOGRAF', 'DRON', 'ASISTENT', 'OSTALO')),
    honorar      NUMERIC(38, 2)
);

CREATE TABLE uplata (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iznos        NUMERIC(38, 2) NOT NULL,
    datum        DATE           NOT NULL,
    vrsta        VARCHAR(255)   NOT NULL CHECK (vrsta IN ('KAPARA', 'RATA', 'OSTATAK')),
    opis         VARCHAR(255),
    vjencanje_id BIGINT         NOT NULL REFERENCES vjencanje (id)
);

CREATE TABLE zadatak (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv        VARCHAR(255) NOT NULL,
    gotovo       BOOLEAN      NOT NULL,
    redoslijed   INTEGER      NOT NULL,
    vjencanje_id BIGINT       NOT NULL REFERENCES vjencanje (id)
);

-- Postgres ne radi indekse za strane ključeve sam; ovo su upiti koji se najčešće izvode
CREATE INDEX idx_vjencanje_tvrtka_datum ON vjencanje (tvrtka_id, datum);
CREATE INDEX idx_uplata_vjencanje ON uplata (vjencanje_id);
CREATE INDEX idx_stavka_vjencanje ON stavka_rasporeda (vjencanje_id);
CREATE INDEX idx_clan_ekipe_vjencanje ON clan_ekipe (vjencanje_id);
CREATE INDEX idx_zadatak_vjencanje ON zadatak (vjencanje_id);
CREATE INDEX idx_email_kod_email ON email_kod (email, svrha);

-- Tipični raspored dana tvrtke, kojim se popunjava novo vjenčanje.
CREATE TABLE predlozak_stavka (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tvrtka_id  BIGINT        NOT NULL REFERENCES tvrtka (id) ON DELETE CASCADE,
    redoslijed INTEGER       NOT NULL,
    vrijeme    TIME,
    naziv      VARCHAR(255)  NOT NULL,
    adresa     VARCHAR(255),
    napomena   VARCHAR(2000)
);
CREATE INDEX predlozak_stavka_tvrtka_idx ON predlozak_stavka (tvrtka_id);

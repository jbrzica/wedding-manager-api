-- Refresh tokeni: dugotrajna prijava u HttpOnly kolačiću, uz kratki access token (JWT).
-- Sprema se samo SHA-256 hash tokena, pa krađa baze ne daje upotrebljive tokene.
-- obitelj povezuje tokene nastale rotacijom iz iste prijave, da se mogu opozvati zajedno.
CREATE TABLE refresh_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    korisnik_id BIGINT                   NOT NULL REFERENCES korisnik (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)              NOT NULL UNIQUE,
    obitelj     VARCHAR(64)              NOT NULL,
    istjece     TIMESTAMP WITH TIME ZONE NOT NULL,
    iskoristen  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX refresh_token_korisnik_idx ON refresh_token (korisnik_id);
CREATE INDEX refresh_token_obitelj_idx ON refresh_token (obitelj);

-- Povijest bitnih promjena (tko je i kada promijenio cijenu, status, uplate...).
-- Bez stranog ključa na vjenčanje, da povijest ostane i nakon trajnog brisanja; zato se pamti i naziv para.
CREATE TABLE promjena (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tvrtka_id       BIGINT                   NOT NULL REFERENCES tvrtka (id) ON DELETE CASCADE,
    vjencanje_id    BIGINT,
    vjencanje_naziv VARCHAR(255),
    korisnik_id     BIGINT,
    korisnik_ime    VARCHAR(255)             NOT NULL,
    vrijeme         TIMESTAMP WITH TIME ZONE NOT NULL,
    opis            VARCHAR(500)             NOT NULL
);
CREATE INDEX promjena_tvrtka_vrijeme_idx ON promjena (tvrtka_id, vrijeme DESC);
CREATE INDEX promjena_vjencanje_idx ON promjena (vjencanje_id);
